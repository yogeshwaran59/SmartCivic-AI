    let currentLanguage = 'en';

    try {
        const stored = localStorage.getItem('smartcivic_lang') || sessionStorage.getItem('smartcivic_lang');
        if (stored && DICTIONARIES[stored]) {
            currentLanguage = stored;
        }
    } catch (e) {}

    function t(key, defaultValue = '') {
        if (!key) return defaultValue;
        const dict = DICTIONARIES[currentLanguage] || DICTIONARIES.en;
        if (dict && dict[key] !== undefined) {
            return dict[key];
        }
        if (DICTIONARIES.en && DICTIONARIES.en[key] !== undefined) {
            return DICTIONARIES.en[key];
        }
        return defaultValue || key;
    }

    function getCurrentLang() {
        return currentLanguage;
    }

    function switchLanguage(lang) {
        if (!DICTIONARIES[lang]) return;
        currentLanguage = lang;
        try {
            localStorage.setItem('smartcivic_lang', lang);
            sessionStorage.setItem('smartcivic_lang', lang);
        } catch (e) {}

        // Update active class on language buttons and dropdown options
        document.querySelectorAll('.btn-lang, .btn-lang-option').forEach(btn => {
            if (btn.dataset.lang === lang) {
                btn.classList.add('active');
            } else {
                btn.classList.remove('active');
            }
        });

        // Update active label in dropdown trigger if present
        const currentLangTag = document.getElementById('current-lang-tag');
        const currentLangName = document.getElementById('current-lang-name');
        const langMap = {
            'en': { tag: 'EN', name: 'English' },
            'kn': { tag: 'KN', name: 'ಕನ್ನಡ' },
            'hi': { tag: 'HI', name: 'हिंदी' },
            'te': { tag: 'TE', name: 'తెలుగు' }
        };
        if (langMap[lang]) {
            if (currentLangTag) currentLangTag.textContent = langMap[lang].tag;
            if (currentLangName) currentLangName.textContent = langMap[lang].name;
        }

        // Update DOM elements with data-i18n
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            const translation = t(key);
            if (translation) {
                el.textContent = translation;
            }
        });

        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            const translation = t(key);
            if (translation) {
                el.placeholder = translation;
            }
        });

        document.querySelectorAll('[data-i18n-title]').forEach(el => {
            const key = el.getAttribute('data-i18n-title');
            const translation = t(key);
            if (translation) {
                el.title = translation;
            }
        });

        // Dispatch languageChanged event
        window.dispatchEvent(new CustomEvent('languageChanged', {
            detail: { language: lang }
        }));
    }

    function getCategoryTranslation(cat) {
        if (!cat) return '';
        const keyMap = {
            pothole: 'cat_pothole',
            garbage: 'cat_garbage',
            drainage: 'cat_open_drain',
            street_light: 'cat_streetlight',
            water_supply: 'cat_water_leakage',
            other: 'cat_other'
        };
        const key = keyMap[cat.toLowerCase()] || `cat_${cat.toLowerCase()}`;
        return t(key, cat.replace('_', ' ').replace(/\b\w/g, l => l.toUpperCase()));
    }

    function getStatusTranslation(status) {
        if (!status) return '';
        const keyMap = {
            'Submitted': 'status_submitted',
            'Verified': 'status_verified',
            'Assigned': 'status_assigned',
            'In Progress': 'status_in_progress',
            'Completed': 'status_completed',
            'Resolved': 'status_resolved',
            'Closed': 'status_closed',
            'Rejected': 'status_rejected',
            'Reopened': 'status_reopened'
        };
        const key = keyMap[status] || `status_${status.toLowerCase().replace(/\s+/g, '_')}`;
        return t(key, status);
    }

    function getPriorityTranslation(priority) {
        if (!priority) return '';
        const keyMap = {
            'High': 'priority_high',
            'Medium': 'priority_medium',
            'Low': 'priority_low'
        };
        const key = keyMap[priority] || `priority_${priority.toLowerCase()}`;
        return t(key, priority);
    }

    function getRoleTranslation(role) {
        if (!role) return '';
        const keyMap = {
            'citizen': 'role_citizen',
            'worker': 'role_worker',
            'authority': 'role_authority',
            'higher_authority': 'role_higher_authority',
            'journalist': 'role_journalist'
        };
        const key = keyMap[role.toLowerCase()] || `role_${role.toLowerCase()}`;
        return t(key, role.replace('_', ' ').toUpperCase());
    }

    function formatDate(dateInput, options = {}) {
        if (!dateInput) return '';
        try {
            const d = new Date(dateInput);
            if (isNaN(d.getTime())) return String(dateInput);
            const localeMap = {
                en: 'en-IN',
                kn: 'kn-IN',
                hi: 'hi-IN',
                te: 'te-IN'
            };
            const loc = localeMap[currentLanguage] || 'en-IN';
            return d.toLocaleString(loc, options);
        } catch (e) {
            return String(dateInput);
        }
    }

